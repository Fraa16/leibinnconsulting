export type PhotoKey = keyof typeof photos;

/** A single Pexels URL at a given width. */
function pexelsUrl(base: string, width: number) {
  return `${base}?auto=compress&cs=tinysrgb&w=${width}`;
}

/** Path to a locally generated variant. */
function localUrl(id: string, width: number, ext: 'avif' | 'webp' | 'jpg') {
  return `/img/${id}-${width}.${ext}`;
}

export interface ResolvedImage {
  src: string;
  srcSet: string;
  /** AVIF/WebP sources, empty while the photograph is still remote. */
  sources: { type: string; srcSet: string }[];
  aspect: number;
}

/** Builds the `src`, `srcset` and modern-format `<source>` list for a photograph. */
export function resolvePhoto(key: PhotoKey): ResolvedImage {
  const photo = photos[key];
  const fallbackWidth = photo.widths[Math.floor(photo.widths.length / 2)];

  if (!USE_LOCAL_PHOTOS) {
    return {
      src: pexelsUrl(photo.remote, fallbackWidth),
      srcSet: photo.widths.map((w) => `${pexelsUrl(photo.remote, w)} ${w}w`).join(', '),
      sources: [],
      aspect: photo.aspect,
    };
  }

  return {
    src: localUrl(photo.id, fallbackWidth, 'jpg'),
    srcSet: photo.widths.map((w) => `${localUrl(photo.id, w, 'jpg')} ${w}w`).join(', '),
    sources: [
      {
        type: 'image/avif',
        srcSet: photo.widths.map((w) => `${localUrl(photo.id, w, 'avif')} ${w}w`).join(', '),
      },
      {
        type: 'image/webp',
        srcSet: photo.widths.map((w) => `${localUrl(photo.id, w, 'webp')} ${w}w`).join(', '),
      },
    ],
    aspect: photo.aspect,
  };
}

/**
 * Locally processed images (generated by `npm run assets` from src/Images).
 * These are always self-hosted.
 */
export const localImages = {
  portrait: { id: 'cedrik', widths: [480, 720, 960], aspect: 3 / 4 },
} as const;

/** Testimonial avatars, generated at 96 and 192 (2× for retina). */
export function resolveAvatar(id: string): ResolvedImage {
  const widths = [96, 192];
  return {
    src: localUrl(id, 96, 'jpg'),
    srcSet: widths.map((w) => `${localUrl(id, w, 'jpg')} ${w}w`).join(', '),
    sources: [
      {
        type: 'image/avif',
        srcSet: widths.map((w) => `${localUrl(id, w, 'avif')} ${w}w`).join(', '),
      },
      {
        type: 'image/webp',
        srcSet: widths.map((w) => `${localUrl(id, w, 'webp')} ${w}w`).join(', '),
      },
    ],
    aspect: 1,
  };
}

export function resolveLocal(key: keyof typeof localImages): ResolvedImage {
  const image = localImages[key];
  const fallbackWidth = image.widths[image.widths.length - 1];
  return {
    src: localUrl(image.id, fallbackWidth, 'jpg'),
    srcSet: image.widths.map((w) => `${localUrl(image.id, w, 'jpg')} ${w}w`).join(', '),
    sources: [
      {
        type: 'image/avif',
        srcSet: image.widths.map((w) => `${localUrl(image.id, w, 'avif')} ${w}w`).join(', '),
      },
      {
        type: 'image/webp',
        srcSet: image.widths.map((w) => `${localUrl(image.id, w, 'webp')} ${w}w`).join(', '),
      },
    ],
    aspect: image.aspect,
  };
}
