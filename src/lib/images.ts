/**
 * Image registry.
 *
 * Every photograph on the site is declared here once, with the widths it is
 * available in, so the <Picture> primitive can emit a correct `srcset` instead of
 * shipping one oversized file to every device. The original build served a single
 * 1920px JPEG to phones.
 *
 * ── Remote vs local ────────────────────────────────────────────────────────────
 * Four photographs are still served from images.pexels.com. Self-hosting them is
 * better on two counts: it removes a third-party request that transmits every
 * visitor's IP address (a DSGVO matter, currently declared in the
 * Datenschutzerklärung) and it removes a DNS + TLS hop from the LCP path.
 *
 * The download was not possible from the build environment this was developed in
 * (network policy blocked images.pexels.com), so they remain remote for now, with
 * responsive `srcset` built from Pexels' own `?w=` parameter — the sizing win
 * applies either way.
 *
 * To finish the job on a machine with open network access:
 *   1. npm run assets:fetch     — downloads the four originals to assets-src/
 *   2. npm run assets           — generates AVIF/WebP variants into public/img/
 *   3. set USE_LOCAL_PHOTOS below to `true`
 * No component changes are needed.
 */

export const USE_LOCAL_PHOTOS = false;

export interface ImageSource {
  /** Identifier, also the filename stem under public/img when self-hosted. */
  id: string;
  /** Remote origin, used until the photograph is self-hosted. */
  remote: string;
  /** Widths to offer in the srcset. */
  widths: number[];
  /** Intrinsic aspect ratio (w / h), for reserving space where no fixed-height container exists. */
  aspect: number;
}

